#!/usr/bin/env bash
# Regenerates nginx/cloudflare-ips.inc and nginx/cloudflare-geo.inc from Cloudflare's published
# ranges (https://www.cloudflare.com/ips). They change rarely; rerun this, review the diff,
# commit, and deploy. nginx trusts CF-Connecting-IP and X-Forwarded-Proto only from these.
set -euo pipefail
cd "$(dirname "$0")/nginx"

ranges="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4; echo; curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"
ranges="$(printf '%s\n' "$ranges" | sed '/^[[:space:]]*$/d')"

# A short or malformed answer must never silently produce an empty trust list.
count="$(printf '%s\n' "$ranges" | wc -l)"
if ((count < 10)) || printf '%s\n' "$ranges" | grep -qvE '^[0-9a-f:.]+/[0-9]+$'; then
    echo "unexpected answer from cloudflare.com/ips ($count lines); leaving the files as they are" >&2
    exit 1
fi

{
    echo "# Generated by update-cloudflare-ips.sh from https://www.cloudflare.com/ips. Do not edit."
    echo "# Requests from these addresses are trusted to carry the visitor's real IP in CF-Connecting-IP."
    printf '%s\n' "$ranges" | sed 's|.*|set_real_ip_from &;|'
} > cloudflare-ips.inc

{
    echo "# Generated by update-cloudflare-ips.sh from https://www.cloudflare.com/ips. Do not edit."
    echo "# Used by geo \$realip_remote_addr: 1 when the TCP peer is Cloudflare."
    printf '%s\n' "$ranges" | sed 's|.*|&  1;|'
} > cloudflare-geo.inc

echo "wrote $count ranges"
